"""InfoLink portraits of the mod's own characters (the game's are InfoPortraits.<bind name>, 64x64, 256 colours).

    python tools\\make_portrait.py <picture.png> <BindName>

writes src\\UnatcoContinues\\Textures\\Portraits\\<BindName>.png (the picture as given, kept as the source) and
UCPortrait_<BindName>.pcx (64x64, 256 colours), then rewrites src\\UnatcoContinues\\Classes\\UCPortraits.uc with one
#exec TEXTURE IMPORT per portrait of that folder. In the game UCPortraits.Find(bindName) gives the texture to the
InfoLink window (UCScene.Say) in place of the game's InfoPortraits. The map editor's Character Creator makes the
picture: window.__characters.portrait('<character id>') (head and shoulders, turned a little, dark background).
Then build.ps1.
"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / 'src' / 'UnatcoContinues' / 'Textures' / 'Portraits'
CLASS = ROOT / 'src' / 'UnatcoContinues' / 'Classes' / 'UCPortraits.uc'

HEAD = """//=============================================================================
// UCPortraits - the InfoLink portraits of the mod's own characters (64x64 like the game's InfoPortraits).
// GENERATED by tools\\make_portrait.py from src\\UnatcoContinues\\Textures\\Portraits: do not edit by hand.
// UCScene.Say asks Find(bindName) after the window has taken the game's portrait (InfoPortraits.<bind name>).
//=============================================================================
class UCPortraits extends Object
	abstract;

"""
TAIL = """
static function Texture Find(string bindName)
{
	if (bindName == "")
		return None;
	return Texture(DynamicLoadObject("UnatcoContinues.UCPortrait_" $ bindName, class'Texture', True));
}
"""


def make(png, bind):
    if not bind.isidentifier():
        raise SystemExit('the bind name is one word (letters, digits, _): %r' % bind)
    FOLDER.mkdir(parents=True, exist_ok=True)
    im = Image.open(png).convert('RGB')
    im.save(FOLDER / (bind + '.png'))
    small = im.resize((64, 64), Image.LANCZOS).quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    small.save(FOLDER / ('UCPortrait_%s.pcx' % bind))


def write_class():
    lines = ['#exec TEXTURE IMPORT NAME=UCPortrait_%s FILE=Textures\\Portraits\\UCPortrait_%s.pcx MIPS=Off' % (p.stem[11:], p.stem[11:])
             for p in sorted(FOLDER.glob('UCPortrait_*.pcx'))]
    CLASS.write_text(HEAD + '\n'.join(lines) + '\n' + TAIL, encoding='latin1')
    return len(lines)


if __name__ == '__main__':
    if len(sys.argv) == 3:
        make(sys.argv[1], sys.argv[2])
    print('%d portraits in %s' % (write_class(), CLASS))
