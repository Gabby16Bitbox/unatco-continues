"""Prop tracks of the Animation Studio as UnrealScript classes, for the mod's scenes in the game's own maps.

The map editor writes a prop's track (where the object in the hand is, frame by frame) into the maps it
rebuilds (UCAnimPropTrack actors, editor/anim_props.py). The mod's scenes also run in maps that are never
rebuilt (Battery Park, the 'Ton's street...), so each track is also a class: UCTrack<Name> extends
UCHeldPropTrack with the frames in its defaultproperties, and the scene spawns it.

    python tools\\make_prop_tracks.py            (after saving the animations in the Studio)

Reads tools\\mapkit\\anims\\baked\\<model>\\<animation>.props.json; writes src\\UnatcoContinues\\Classes\\UCTrack*.uc.
A track has 64 frames at most (one chunk: spawned actors have no names to chain chunks by).
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BAKED = ROOT / 'tools' / 'mapkit' / 'anims' / 'baked'
CLASSES = ROOT / 'src' / 'UnatcoContinues' / 'Classes'

# (animation, baked model, prop id, class to write, the look (a class), the follower that does the rest[, size]):
# size turns the Studio's scale of the prop into the look's (the look's own DrawScale is in its class)
TRACKS = [
    ('UCFlareLight', 'DeusExCharacters.GM_Suit', 'flare', 'UCTrackFlareLight', 'DeusEx.Flare', 'UCHeldFlare'),
    ('UCFlareHold', 'DeusExCharacters.GM_Suit', 'flare', 'UCTrackFlareHold', 'DeusEx.Flare', 'UCHeldFlare'),
    # previewed in the Studio as a flare (DrawScale 1); UCCigarette is that flare model at 0.33: the same size
    # is the Studio's scale / 0.33 (Gabby placed and sized it there, 18 Oct 2026: a flare at 0.5)
    ('UCLeanSmoke', 'DeusExCharacters.GM_Suit', 'cig', 'UCTrackLeanSmoke', 'UnatcoContinues.UCCigarette', 'UCCigaretteHeld', 1 / 0.33),
]

HEADER = """//=============================================================================
// %(cls)s - GENERATED by tools\\make_prop_tracks.py from the Animation Studio's bake of %(anim)s on
// %(model)s (prop "%(prop)s", %(frames)d frames): do not edit, save the animation in the Studio and run the
// script again. Spawned by the scene that uses the animation (see UCHeldPropTrack).
//=============================================================================
class %(cls)s extends UCHeldPropTrack;

defaultproperties
{
"""


def write(anim, model, prop, cls, look, follower, size=1.0):
    doc = json.loads((BAKED / model / (anim + '.props.json')).read_text(encoding='utf-8'))
    frames = doc['frames']
    track = next(p for p in doc['props'] if p['id'] == prop)
    if frames > 64:
        raise SystemExit('%s has %d frames: a runtime track holds 64 at most' % (anim, frames))
    lines = [HEADER % dict(cls=cls, anim=anim, model=model, prop=prop, frames=frames)]
    props = [
        ('PropActor', "Class'UnatcoContinues.%s'" % follower),
        ('AnimationName', anim),
        ('ModelName', model.split('.')[-1]),
        ('ModelPackage', 'UCAnims'),
        ('PropClass', '"%s"' % look),
        ('PropScale', '%.6f' % (track['scale'] * size)),
        ('FrameCount', str(frames)),
        ('StartFrame', '0'),
        ('SampleCount', str(frames)),
    ]
    for i, s in enumerate(track['samples']):
        props.append(('Positions(%d)' % i, '(X=%.6f,Y=%.6f,Z=%.6f)' % tuple(s['position'])))
        props.append(('Rotations(%d)' % i, '(Pitch=%d,Yaw=%d,Roll=%d)' % tuple(round(v) for v in s['rotation'])))
    lines += ['\t%s=%s\n' % kv for kv in props]
    lines.append('}\n')
    out = CLASSES / (cls + '.uc')
    out.write_text(''.join(lines), encoding='utf-8', newline='\n')
    print('wrote %s (%d frames)' % (out.name, frames))


def main():
    for row in TRACKS:
        write(*row)


if __name__ == '__main__':
    main()
